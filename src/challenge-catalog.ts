const catalog = new Map<number, Challenge>([[11, task11]]);
export const CHALLENGE_TOPICS = [...catalog.keys()];
export const challengeFor = (topic: number) => catalog.get(topic);

export function challengeView(challenge: Challenge, solved: ReadonlySet<string>) {
    const lesson = challenge.lesson.filter(({ id }) => solved.has(id)).length;
    const practice = challenge.practice.filter(({ id }) => solved.has(id)).length;
    const exercise = [...challenge.lesson, ...challenge.practice].find(({ id }) => !solved.has(id));
    const phase = lesson < challenge.lesson.length ? 'lesson' as const : exercise ? 'practice' as const : 'complete' as const;
    return {
        title: challenge.title, phase,
        lesson: { solved: lesson, total: challenge.lesson.length },
        practice: { solved: practice, total: challenge.practice.length },
        exercise: exercise ? { id: exercise.id, title: exercise.title, prompt: exercise.prompt, hint: exercise.hint } : null,
    };
}

export function challengeSession(challenge: Challenge, solved: ReadonlySet<string>,
    attempt: { startedAt: number; finishedAt: number | null } | null, now: number,
) {
    const view = challengeView(challenge, solved);
    const timer = attempt && { ...attempt, deadline: attempt.startedAt + challenge.limitMs, asOf: now };
    const expired = view.phase === 'lesson' && timer !== null && now >= timer.deadline;
    return {
        ...view, limitMs: challenge.limitMs, timer, expired,
        exercise: view.phase === 'lesson' && (!timer || expired) ? null : view.exercise,
    };
}
